const IMAGE_MAPS: Record<Density, Record<string, ImageSource>> = {
  '1x': IMAGES_1X,
  '2x': IMAGES_2X,
  '3x': IMAGES_3X,
};

export function getCardImageSource(card: CardDefinition): ImageSource {
  return IMAGE_MAPS[getDensity()][card.id];
}

export function getCardBackSource(): ImageSource {
  // Metro resolves @2x/@3x variants from the base filename — don't require them directly
  return require('../../assets/cards/back/card-back.png');
}
