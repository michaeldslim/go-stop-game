import type { CardDefinition } from '../types/hwatu';

type Density = '1x' | '2x' | '3x';

function getDensity(): Density {
  const scale = PixelRatio.get();
  if (scale >= 3) return '3x';
  if (scale >= 2) return '2x';
  return '1x';
}

